# generates manifests/grafana.yaml: Grafana 13.2.4 with a provisioned Prometheus data source and the
# "allcsvideos cost" dashboard built from OpenCost metrics (lab prices, see opencost-values.yaml)
import json, os
H = os.path.dirname(os.path.abspath(__file__))
DS = {"type": "prometheus", "uid": "prom"}
CPU = 'sum by (namespace) (container_cpu_allocation{namespace=~"allcs-.*"} * on (node) group_left() avg by (node) (node_cpu_hourly_cost))'
RAM = 'sum by (namespace) (container_memory_allocation_bytes{namespace=~"allcs-.*"} / 1024 / 1024 / 1024 * on (node) group_left() avg by (node) (node_ram_hourly_cost))'
NS_COST = f'({CPU}) + ({RAM})'
TEAM = ('sum by (label_team) ((container_cpu_allocation{namespace=~"allcs-.*"} * on (node) group_left() avg by (node) (node_cpu_hourly_cost)'
        ' + container_memory_allocation_bytes{namespace=~"allcs-.*"} / 1073741824 * on (node) group_left() avg by (node) (node_ram_hourly_cost))'
        ' * on (namespace, pod) group_left (label_team) max by (namespace, pod, label_team) (kube_pod_labels))')
REQ = 'sum by (namespace) (kube_pod_container_resource_requests{resource="cpu", namespace=~"allcs-.*"})'
USE = 'sum by (namespace) (rate(container_cpu_usage_seconds_total{container!="", namespace=~"allcs-.*"}[5m]))'
def ts(i, title, exprs, unit, x, y, w, h, legend=True, decimals=None):
    p = {"id": i, "type": "timeseries", "title": title, "datasource": DS, "gridPos": {"x": x, "y": y, "w": w, "h": h},
         "targets": [{"refId": chr(65 + k), "datasource": DS, "expr": e, "legendFormat": l} for k, (e, l) in enumerate(exprs)],
         "fieldConfig": {"defaults": {"unit": unit, "custom": {"lineWidth": 2, "fillOpacity": 10}}, "overrides": []},
         "options": {"legend": {"showLegend": legend, "displayMode": "list", "placement": "bottom"}, "tooltip": {"mode": "multi"}}}
    if decimals is not None: p["fieldConfig"]["defaults"]["decimals"] = decimals
    return p
def stat(i, title, expr, unit, x, y, w, h, decimals=4):
    return {"id": i, "type": "stat", "title": title, "datasource": DS, "gridPos": {"x": x, "y": y, "w": w, "h": h},
            "targets": [{"refId": "A", "datasource": DS, "expr": expr}],
            "fieldConfig": {"defaults": {"unit": unit, "decimals": decimals, "color": {"mode": "fixed", "fixedColor": "blue"}}, "overrides": []},
            "options": {"reduceOptions": {"calcs": ["lastNotNull"]}, "colorMode": "value", "graphMode": "area", "textMode": "value"}}
panels = [
    stat(1, "Cluster cost per hour (node price)", "sum(node_total_hourly_cost)", "currencyUSD", 0, 0, 6, 5),
    stat(2, "Cluster cost per month (x 730 h)", "sum(node_total_hourly_cost) * 730", "currencyUSD", 6, 0, 6, 5, 2),
    stat(3, "allcsvideos allocated per hour", f"sum({NS_COST})", "currencyUSD", 12, 0, 6, 5),
    stat(4, "Idle share of the node", f"1 - sum({NS_COST}) / sum(node_total_hourly_cost)", "percentunit", 18, 0, 6, 5, 1),
    ts(5, "Cost per hour by namespace (allocated = max of request and usage)", [(NS_COST, "{{namespace}}")], "currencyUSD", 0, 5, 12, 9, decimals=4),
    ts(6, "Cost per hour by team label", [(TEAM, "{{label_team}}")], "currencyUSD", 12, 5, 12, 9, decimals=4),
    ts(7, "CPU requested vs used (cores)", [(REQ, "{{namespace}} requested"), (USE, "{{namespace}} used")], "short", 0, 14, 24, 9, decimals=2),
]
dash = {"uid": "allcs-cost", "title": "allcsvideos cost", "tags": ["finops", "opencost"], "timezone": "browser",
        "schemaVersion": 41, "refresh": "1m", "time": {"from": "now-3h", "to": "now"}, "panels": panels}
ds = {"apiVersion": 1, "datasources": [{"name": "Prometheus", "uid": "prom", "type": "prometheus", "access": "proxy",
      "url": "http://prometheus.monitoring:9090", "isDefault": True, "jsonData": {"timeInterval": "15s"}}]}
prov = {"apiVersion": 1, "providers": [{"name": "finops", "folder": "FinOps", "type": "file", "options": {"path": "/var/lib/grafana/dashboards"}}]}
ind = lambda s, n: "\n".join(" " * n + l for l in s.split("\n"))
y = f"""# Grafana 13.2.4 (lab): anonymous viewer access, a provisioned Prometheus data source and the allcsvideos cost dashboard
# GENERATED by grafana/make_dash.py (python3 grafana/make_dash.py rewrites this file)
apiVersion: v1
kind: ConfigMap
metadata: {{name: grafana-provisioning, namespace: monitoring}}
data:
  datasources.yaml: |
{ind(json.dumps(ds, indent=2), 4)}
  dashboards.yaml: |
{ind(json.dumps(prov, indent=2), 4)}
---
apiVersion: v1
kind: ConfigMap
metadata: {{name: grafana-dashboards, namespace: monitoring}}
data:
  allcs-cost.json: |
{ind(json.dumps(dash, indent=2), 4)}
---
apiVersion: apps/v1
kind: Deployment
metadata: {{name: grafana, namespace: monitoring, labels: {{app: grafana}}}}
spec:
  replicas: 1
  selector: {{matchLabels: {{app: grafana}}}}
  template:
    metadata: {{labels: {{app: grafana}}}}
    spec:
      containers:
      - name: grafana
        image: grafana/grafana:13.2.4
        env:
        - {{name: GF_AUTH_ANONYMOUS_ENABLED, value: "true"}}      # lab only
        - {{name: GF_AUTH_ANONYMOUS_ORG_ROLE, value: Viewer}}
        - {{name: GF_SECURITY_ADMIN_PASSWORD, value: demo-password-123}}   # FAKE lab password
        - {{name: GF_ANALYTICS_REPORTING_ENABLED, value: "false"}}
        - {{name: GF_ANALYTICS_CHECK_FOR_UPDATES, value: "false"}}
        - {{name: GF_NEWS_NEWS_FEED_ENABLED, value: "false"}}
        ports: [{{containerPort: 3000}}]
        resources:
          requests: {{cpu: 100m, memory: 256Mi}}
          limits: {{memory: 768Mi}}
        volumeMounts:
        - {{name: prov, mountPath: /etc/grafana/provisioning/datasources/ds.yaml, subPath: datasources.yaml}}
        - {{name: prov, mountPath: /etc/grafana/provisioning/dashboards/db.yaml, subPath: dashboards.yaml}}
        - {{name: dash, mountPath: /var/lib/grafana/dashboards}}
      volumes:
      - {{name: prov, configMap: {{name: grafana-provisioning}}}}
      - {{name: dash, configMap: {{name: grafana-dashboards}}}}
---
apiVersion: v1
kind: Service
metadata: {{name: grafana, namespace: monitoring}}
spec:
  selector: {{app: grafana}}
  ports: [{{port: 3000, targetPort: 3000}}]
"""
open(os.path.join(H, "..", "manifests", "grafana.yaml"), "w").write(y)
print("ok")
